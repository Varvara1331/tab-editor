/**
 * Компонент викторины (теста) для проверки знаний после прочтения главы
 */
const QuizSection: React.FC<{ quiz: Quiz; onComplete: (passed: boolean, score: number) => void }> = ({ quiz, onComplete }) => {
  const [answers, setAnswers] = useState<Record<string, string | string[]>>({});
  const [submitted, setSubmitted] = useState(false);
  const [score, setScore] = useState(0);

  const handleAnswer = (questionId: string, answer: string | string[]) => {
    setAnswers(prev => ({ ...prev, [questionId]: answer }));
  };

  const handleSubmit = () => {
    let correctCount = 0;
    quiz.questions.forEach(q => {
      const userAnswer = answers[q.id];
      if (userAnswer) {
        if (Array.isArray(q.correctAnswer)) {
          if (Array.isArray(userAnswer) && 
              q.correctAnswer.length === userAnswer.length &&
              q.correctAnswer.every(a => userAnswer.includes(a))) {
            correctCount++;
          }
        } else if (userAnswer === q.correctAnswer) {
          correctCount++;
        }
      }
    });
    const finalScore = (correctCount / quiz.questions.length) * 100;
    setScore(finalScore);
    setSubmitted(true);
  };

  const handleRetry = () => {
    setAnswers({});
    setSubmitted(false);
    setScore(0);
  };

  if (submitted) {
    const passed = score >= quiz.passingScore;
    return (
      <div className="quiz-results">
        <h4>{passed ? <Trophy size={24} /> : <Target size={24} />}{passed ? 'Отлично!' : 'Попробуйте ещё раз'}</h4>
        <div className="score-display">
          <span className="score-value">{Math.round(score)}%</span>
          <div className="score-bar"><div className="score-fill" style={{ width: `${score}%` }} /></div>
        </div>
        <div className="quiz-actions">
          <button className="retry-btn" onClick={handleRetry}><RotateCcw size={16} />Пройти заново</button>
          <button className="continue-btn" onClick={() => onComplete(passed, score)}>Продолжить <ChevronRight size={16} /></button>
        </div>
      </div>
    );
  }

  return (
    <div className="quiz-section">
      <h4><GraduationCap size={24} />Проверьте свои знания</h4>
      {quiz.questions.map((q, idx) => (
        <div key={q.id} className="quiz-question">
          <p className="question-text"><span className="question-number">{idx + 1}</span>{q.text}</p>
          {q.type === 'multiple-choice' && q.options && (
            <div className="options">
              {q.options.map(opt => (
                <label key={opt} className="option-label">
                  <input type="radio" name={q.id} value={opt} checked={answers[q.id] === opt} onChange={(e) => handleAnswer(q.id, e.target.value)} />
                  <span>{opt}</span>
                </label>
              ))}
            </div>
          )}
          {q.type === 'true-false' && q.options && (
            <div className="options">
              {q.options.map(opt => (
                <label key={opt} className="option-label">
                  <input type="radio" name={q.id} value={opt} checked={answers[q.id] === opt} onChange={(e) => handleAnswer(q.id, e.target.value)} />
                  <span>{opt === 'True' ? '✅ Правда' : '❌ Ложь'}</span>
                </label>
              ))}
            </div>
          )}
        </div>
      ))}
      <button className="submit-quiz-btn" onClick={handleSubmit}><CheckCircle size={18} />Проверить ответы</button>
    </div>
  );
};

